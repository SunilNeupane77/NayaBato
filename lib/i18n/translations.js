// Function to get translation for a specific key
export const getTranslation = (locale, key) => {
  const keys = key.split('.');
  let result = translations[locale];
  
  for (const k of keys) {
    if (result && result[k]) {
      result = result[k];
    } else {
      // Fallback to English if translation not found
      let fallback = translations['en'];
      for (const k of keys) {
        if (fallback && fallback[k]) {
          fallback = fallback[k];
        } else {
          return key; // Return the key as is if no translation found
        }
      }
      return fallback;
    }
  }
  
  return result;
};
